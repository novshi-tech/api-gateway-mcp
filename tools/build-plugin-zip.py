#!/usr/bin/env python3
"""Packages a plugin under plugins/ as a zip for uploading to Claude.

Usage: tools/build-plugin-zip.py [plugin-name ...]   (default: every plugin)
Writes dist/<plugin-name>-<version>.zip for each.

       tools/build-plugin-zip.py --bundle
Writes every plugin, zipped and base64-encoded, into dist/plugins.js (with its .d.ts) for
src/plugins.ts to import, so the gateway offers them on its web UI. They go into the Worker
itself rather than its static assets: uploading assets needs a per-upload token in the
Authorization header, which a proxy that injects the Cloudflare API token overwrites.
npm run deploy / dev / typecheck and the tests run this first.
"""
import base64
import io
import json
import os
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLUGINS = os.path.join(ROOT, "plugins")


def main():
    args = sys.argv[1:]
    if args == ["--bundle"]:
        bundle()
        return
    for name in args or sorted(os.listdir(PLUGINS)):
        print(build(name, os.path.join(ROOT, "dist")))


def manifest(name):
    with open(os.path.join(PLUGINS, name, ".claude-plugin", "plugin.json"), encoding="utf-8") as f:
        return json.load(f)


def build(name, out_dir):
    version = manifest(name)["version"]
    os.makedirs(out_dir, exist_ok=True)
    out = os.path.join(out_dir, f"{name}-{version}.zip")
    with open(out, "wb") as f:
        f.write(zip_bytes(name))
    return out


def zip_bytes(name):
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as z:
        for root, dirs, files in os.walk(os.path.join(PLUGINS, name)):
            dirs[:] = sorted(d for d in dirs if d != "__pycache__")
            for file in sorted(files):
                path = os.path.join(root, file)
                # A fixed time, so the same sources make the same zip.
                info = zipfile.ZipInfo(os.path.relpath(path, PLUGINS), date_time=(1980, 1, 1, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = (os.stat(path).st_mode & 0o777) << 16
                with open(path, "rb") as f:
                    z.writestr(info, f.read())
    return buffer.getvalue()


DECLARATION = """export interface BundledPlugin {
  name: string;
  version: string;
  description: string;
  dependencies: string[];
  marketplace: string | null;
  zip: string;
}
declare const bundle: { marketplace: string; plugins: BundledPlugin[] };
export default bundle;
"""


# Each plugin as the marketplace lists it (.claude-plugin/marketplace.json), in its order.
def bundle():
    with open(os.path.join(ROOT, ".claude-plugin", "marketplace.json"), encoding="utf-8") as f:
        market = json.load(f)
    listed = {p["name"]: p for p in market["plugins"]}
    names = [p["name"] for p in market["plugins"] if os.path.isdir(os.path.join(PLUGINS, p["name"]))]
    names += sorted(n for n in os.listdir(PLUGINS) if n not in listed)
    plugins = []
    for name in names:
        plugin = manifest(name)
        entry = listed.get(name, {})
        source = entry.get("source")
        plugins.append(
            {
                "name": name,
                "version": plugin["version"],
                "description": entry.get("description") or plugin.get("description", ""),
                "dependencies": entry.get("dependencies", []),
                "marketplace": source.get("url") if isinstance(source, dict) else None,
                "zip": base64.b64encode(zip_bytes(name)).decode("ascii"),
            }
        )
    out_dir = os.path.join(ROOT, "dist")
    os.makedirs(out_dir, exist_ok=True)
    body = json.dumps({"marketplace": market["name"], "plugins": plugins}, ensure_ascii=False, indent=1)
    with open(os.path.join(out_dir, "plugins.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build-plugin-zip.py --bundle. Do not edit.\nexport default " + body + ";\n")
    with open(os.path.join(out_dir, "plugins.d.ts"), "w", encoding="utf-8") as f:
        f.write(DECLARATION)
    print(os.path.join(out_dir, "plugins.js"))


if __name__ == "__main__":
    main()
